class Translator:
    def __init__(self, lang: str = "en"):
        self.lang = lang if lang in LANGS else "en"

    def __call__(self, key: str) -> str:
        values = _T.get(key)
        if not values:
            return key
        return values[LANGS.index(self.lang)]
